def corpus():
    c = defaultdict(lambda: defaultdict(Counter))
    for f in glob.glob(os.path.join(TOK, "*.json")):
        t = json.load(open(f))
        tk = t.get("tokens", [])
        if "use:house" not in tk:
            continue
        b = (t.get("place") or {}).get("band")
        for x in tk:
            fam, _, val = x.partition(":")
            c[b][fam][val] += 1
    return c


