def business(r, typ, surnames, town, place_words):
    if typ == "vacant":
        return {"business": "", "type": "vacant", "sign": "FOR LEASE"}
    word = TRADE.get(typ, typ.replace("_", " ").title())
    style = r.random()
    if style < 0.55:
        name = f"{r.choice(surnames)} {word}" if word else r.choice(surnames)
    elif style < 0.8:
        name = f"{r.choice(place_words)} {word}"
    else:
        name = f"{r.choice(surnames)} & {r.choice(surnames)} {word}"
    return {"business": name, "type": typ, "sign": name.upper(), "sign_style": r.choice(["projecting", "flat_board", "flat_board", "awning_lettering"]),
            "awning": r.random() < 0.45}


