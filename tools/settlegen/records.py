def rnd_for(seed, *key):
    h = hashlib.blake2b("|".join(map(str, (seed,) + key)).encode(), digest_size=8).digest()
    return random.Random(int.from_bytes(h, "little"))


def wpick(r, weights):
    items = [(k, w) for k, w in weights.items() if w > 0]
    tot = sum(w for _, w in items)
    x = r.random() * tot
    for k, w in items:
        x -= w
        if x <= 0:
            return k
    return items[-1][0]


