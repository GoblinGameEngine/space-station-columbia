def jitter(hexc, r, amt=10):
    c = [int(hexc[i:i + 2], 16) for i in (1, 3, 5)]
    c = [max(0, min(255, v + r.randint(-amt, amt))) for v in c]
    return "#%02x%02x%02x" % tuple(c)


class Rules:
    def __init__(self, seed):
        self.seed = seed
        self.c = corpus()
        self.face = {}
        import canon_lineages as LI
        self.surnames = [l["surname"] for l in LI.LINEAGES if " " not in l["surname"]] or ["Smith"]

    def form_weights(self, band):
        """The band's prior blended with the corpus's measured forms (weight by how many samples there are)."""
        w = dict(PRIOR_FORM[band])
        meas = Counter()
        for tb in TOKEN_BAND[band]:
            meas.update(self.c.get(tb, {}).get("form", Counter()))
        n = sum(meas.values())
        if n:
            k = min(0.6, n / 120.0)                         # (trust the corpus up to 60 % where it has 70+ houses)
            tot = sum(w.values())
            w = {f: (1 - k) * v / tot for f, v in w.items()}
            for f, v in meas.items():
                if f in ARCH:
                    w[f] = w.get(f, 0.0) + k * v / n
        return w

    def condition(self, band, r):
        old = band in ("rail", "streetcar")
        return wpick(r, {"kept": 72, "worn": 20 if old else 12, "shabby": 7 if old else 3, "new": 0 if old else 3})

    def face_theme(self, face, band, r):
        """03_compatibility: a block face built by one builder in one decade shares a form and a storey count."""
        if face not in self.face:
            fr = rnd_for(self.seed, "face", face)
            f = wpick(fr, self.form_weights(band))
            self.face[face] = (f, fr.uniform(0.45, 0.75) if band in ("postwar", "suburban", "late", "current") else fr.uniform(0.3, 0.55))
        return self.face[face]

